"""Regression tests for bugs found in the 1.5.0 bug check (plain Python - run:  python tests/test_regressions.py).

Every book used here is generated by the test itself, so nothing private is needed and the checks run on
GitHub Actions too. The window checks need a display (on Linux CI they run under xvfb-run); without one
they are skipped and say so.
"""
import os
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
TMP = tempfile.mkdtemp(prefix="bf_regress_")
os.environ["APPDATA"] = os.path.join(TMP, "appdata")          # keep the user's real settings out of it
os.environ["HOME"] = os.path.join(TMP, "home")
os.makedirs(os.environ["APPDATA"], exist_ok=True)
os.makedirs(os.environ["HOME"], exist_ok=True)

import pdfplumber                                                     # noqa: E402
import bf_impose  # noqa: E402,F401  (registers binding defaults)
from bf_core import DEFAULTS, load_book, apply_info, plain          # noqa: E402
from bf_build import run_build, build_preview                       # noqa: E402

FAILS = []


def check(cond, msg):
    print(("PASS  " if cond else "FAIL  ") + msg)
    if not cond:
        FAILS.append(msg)


def build(paste=None, path=None, **kw):
    s = dict(DEFAULTS)
    s.update(out_dir=tempfile.mkdtemp(dir=TMP), fmt_impose=False, open_when_done=False)
    if paste is not None:
        s.update(source_mode="paste", paste_text=paste)
    else:
        s.update(source_mode="file", source_path=path)
    s.update(kw)
    book = apply_info(load_book(s, s.get("paste_text", "")), s)
    _folder, made, _notes = run_build(book, s, lambda m: None)
    return book, made, s


def pdf_text(path):
    with pdfplumber.open(path) as p:
        return "\n".join(pg.extract_text() or "" for pg in p.pages)


LONG = "".join(f"\n\nChapter {n}\n\n" + " ".join(f"Sentence {k} of chapter {n} has ordinary words in it." for k in range(160))
               for n in range(1, 5))

# ---------------------------------------------------------------- 1. inside (spine) margin on the correct side
# Bug: ReportLab kept each page template for two pages in a row, so on every other pair of pages the wide
# inside margin ended up on the outside edge (text ran into the glued spine).
_b, made, s = build(paste=LONG, margin_inner=2.0, margin_outer=0.5, pn_position="None", running_heads=False)
bad = []
with pdfplumber.open(made[0]) as p:
    for i, pg in enumerate(p.pages):
        words = pg.extract_words()
        if not words:
            continue
        left, right = min(w["x0"] for w in words), max(w["x1"] for w in words)
        if (i + 1) % 2 == 1 and left < 2.0 * 72 - 1.5:               # right-hand page: spine on the left
            bad.append(i + 1)
        if (i + 1) % 2 == 0 and right > pg.width - 2.0 * 72 + 1.5:   # left-hand page: spine on the right
            bad.append(i + 1)
    n_pages = len(p.pages)
check(n_pages >= 8 and not bad, f"inside margin is on the spine side of all {n_pages} pages (wrong on {bad[:6]})")

# ---------------------------------------------------------------- 2. text under a Part heading is printed
# Bug: an epigraph or introduction under "PART ONE" was left out of the print PDF (the EPUB/Word/HTML/text
# outputs had it).


def xhtml(body):
    return ('<?xml version="1.0" encoding="utf-8"?><html xmlns="http://www.w3.org/1999/xhtml"><head><title>x</title>'
            '</head><body>' + body + '</body></html>')


docs = []
for p_no, part in enumerate(("PART ONE", "PART TWO")):
    docs.append(f"<h2>{part}</h2><p>Epigraph {p_no + 1}: the river remembers every stone.</p>")
    for c in range(3):
        n = p_no * 3 + c + 1
        docs.append(f"<h3>Chapter {n}</h3>" + "".join(f"<p>Paragraph {k} of chapter {n}.</p>" for k in range(5)))
epub = os.path.join(TMP, "parts.epub")
with zipfile.ZipFile(epub, "w") as z:
    z.writestr(zipfile.ZipInfo("mimetype"), "application/epub+zip")
    z.writestr("META-INF/container.xml", '<?xml version="1.0"?><container version="1.0" xmlns="urn:oasis:names:tc:'
               'opendocument:xmlns:container"><rootfiles><rootfile full-path="c.opf" media-type="application/oebps-'
               'package+xml"/></rootfiles></container>')
    for i, d in enumerate(docs):
        z.writestr(f"d{i}.xhtml", xhtml(d))
    man = "".join(f'<item id="d{i}" href="d{i}.xhtml" media-type="application/xhtml+xml"/>' for i in range(len(docs)))
    spine = "".join(f'<itemref idref="d{i}"/>' for i in range(len(docs)))
    z.writestr("c.opf", '<?xml version="1.0"?><package xmlns="http://www.idpf.org/2007/opf" version="3.0"><metadata '
               'xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:title>Parts Test</dc:title></metadata>'
               f'<manifest>{man}</manifest><spine>{spine}</spine></package>')
for start in ("New page", "Continuous"):
    book, made, s = build(path=epub, chapter_start=start, fmt_txt=True)
    parts = [c for c in book.chapters if c.level == 0]
    text = pdf_text(made[0])
    check(len(parts) == 2 and text.count("Epigraph") == 2 and text.count("the river remembers") == 2,
          f"text under Part headings is printed ({start}): {text.count('Epigraph')} of 2 epigraphs")
    txt = open([m for m in made if m.endswith(".txt")][0], encoding="utf-8").read()
    check(txt.count("Epigraph") == 2, f"plain-text output still has both epigraphs ({start})")

# ---------------------------------------------------------------- 3. drop cap paragraph laid out twice
# Bug: when a drop-cap paragraph had to be laid out again (moved to the next page, or a second pass for the
# contents page), the build stopped with "'DropLetter' object has no attribute '_unRestrictSize'".
import io                                                          # noqa: E402
from reportlab.platypus import Paragraph, ImageAndFlowables       # noqa: E402
from reportlab.lib.styles import getSampleStyleSheet               # noqa: E402
from reportlab.pdfgen.canvas import Canvas                         # noqa: E402
from bf_pdf import DropLetter                                      # noqa: E402
try:
    f = ImageAndFlowables(DropLetter("H", "Times-Roman", 13, 18, 3), [Paragraph("Words " * 80,
                                                                                 getSampleStyleSheet()["Normal"])])
    f.canv = Canvas(io.BytesIO())
    f.wrap(300, 600)
    f.wrap(300, 120)
    ok = True
except Exception as e:                    # noqa: BLE001
    ok, err = False, e
check(ok, "drop-cap paragraph can be laid out again with a different amount of space" + ("" if ok else f" ({err})"))
crashes = []
for size, lines in ((13.0, 3), (20.0, 5), (24.0, 2)):
    try:
        build(paste="Chapter 1\n\nChapter Notes\n\n" + "A note before the story. " * 30 + LONG.split("Chapter 2")[0][12:],
              page_size="Mass Market (4.25 x 6.87 in)", body_size=size, drop_cap=True, drop_cap_lines=lines,
              chapter_start="Continuous")
        build(paste=LONG, page_size="Mass Market (4.25 x 6.87 in)", body_size=size, drop_cap=True,
              drop_cap_lines=lines, chapter_start="Continuous")
    except Exception as e:                # noqa: BLE001
        crashes.append((size, lines, f"{type(e).__name__}: {e}"))
check(not crashes, f"drop caps on a small page with big text build without errors {crashes[:1]}")

# ---------------------------------------------------------------- 4. Word: words inside links are kept
# Bug: python-docx's paragraph.runs leaves out runs inside hyperlinks, so linked words vanished.
import docx                                                        # noqa: E402
from docx.oxml.shared import OxmlElement, qn                       # noqa: E402
d = docx.Document()
for n in (1, 2):
    d.add_heading(f"Chapter {n}", 1)
    p = d.add_paragraph("Visit ")
    rid = d.part.relate_to("https://example.com", "http://schemas.openxmlformats.org/officeDocument/2006/"
                           "relationships/hyperlink", is_external=True)
    h = OxmlElement("w:hyperlink")
    h.set(qn("r:id"), rid)
    r = OxmlElement("w:r")
    t = OxmlElement("w:t")
    t.text = "the linked words"
    r.append(t)
    h.append(r)
    p._p.append(h)
    p.add_run(" and carry on reading.")
wd = os.path.join(TMP, "links.docx")
d.save(wd)
s = dict(DEFAULTS)
s.update(source_path=wd)
book = load_book(s)
paras = [plain(b.text) for c in book.chapters for b in c.blocks]
check(paras.count("Visit the linked words and carry on reading.") == 2, f"Word import keeps the words of links {paras[:2]}")

# ---------------------------------------------------------------- 5. packaged macOS/Linux preview
# Bug: Pillow finds Tk through PIL._tkinter_finder on macOS and Linux. PyInstaller did not bundle it, so the
# packaged app's preview window opened empty. BookForge.py must import it so every build includes it.
src = open(os.path.join(ROOT, "BookForge.py"), encoding="utf-8").read()
check("from PIL import _tkinter_finder" in src, "BookForge.py imports PIL._tkinter_finder (so PyInstaller bundles it)")
try:
    from PIL import _tkinter_finder  # noqa: F401
    check(True, "PIL._tkinter_finder is importable")
except ImportError as e:
    check(False, f"PIL._tkinter_finder is importable ({e})")

# ---------------------------------------------------------------- 6. the window (needs a display)
try:
    import tkinter as tk
    probe = tk.Tk()
    probe.destroy()
    have_display = True
except Exception as e:                     # noqa: BLE001
    have_display = False
    print(f"SKIP  window checks (no display: {e})")

if have_display:
    import time
    import BookForge as BF
    app = BF.App()
    errors = []
    app.report_callback_exception = lambda *a: errors.append(a[1])

    def pump(sec=0.4):
        end = time.time() + sec
        while time.time() < end:
            app.update()
            time.sleep(0.02)

    pump()
    res = build_preview(apply_info(load_book(dict(DEFAULTS, source_mode="paste"), LONG), dict(DEFAULTS)),
                        dict(DEFAULTS, fmt_impose=True), log=lambda m: None)
    win = BF.PreviewWindow(app, res)
    pump()
    ph = getattr(win, "photo", None)
    check(ph is not None and ph.width() > 100 and ph.height() > 100 and bool(win.canvas.find_all()),
          "preview window draws the page")
    # mouse wheel: Linux sends Button-4/5, macOS small MouseWheel steps
    win.zoom.set("Actual size")
    win.render()
    pump(0.2)
    y0 = win.canvas.yview()[0]
    for _ in range(3):
        win.canvas.event_generate("<Button-5>", x=10, y=10)
    pump(0.2)
    y1 = win.canvas.yview()[0]
    check(y1 > y0, "Linux-style mouse wheel (Button-5) scrolls the preview")
    win.canvas.event_generate("<MouseWheel>", delta=1, x=10, y=10)
    pump(0.2)
    check(win.canvas.yview()[0] < y1, "small macOS-style wheel step scrolls the preview")
    win.close()
    app.geometry("900x500")
    app.shelf.select(4)
    pump(0.5)
    page = app.pages[4]
    w = page.inner.winfo_children()[0]
    y0 = page.canvas.yview()[0]
    for _ in range(3):
        w.event_generate("<Button-5>", x=5, y=5)
    pump(0.2)
    check(page.canvas.yview()[0] > y0, "Linux-style mouse wheel (Button-5) scrolls a settings page")
    # one message that fails to be handled must not stop BookForge listening (builds would never finish)
    app.q.put(("preview", {}))
    app.q.put(("log", "MESSAGE AFTER A FAILURE"))
    pump(1.0)
    check("MESSAGE AFTER A FAILURE" in app.logbox.get("1.0", "end"),
          "after one message fails, BookForge still handles the next ones")
    app.busy = False
    app.destroy()

print(f"\n{len(FAILS)} failure(s)")
sys.exit(1 if FAILS else 0)
